-- Careers (careers/*). These tables existed before Flyway on databases that ran the
-- careers release with ddl-auto=update, hence IF NOT EXISTS throughout.
-- Enums are VARCHAR with a CHECK (as Hibernate creates them on PostgreSQL). Résumé bytes
-- need BLOB on H2 and BYTEA on PostgreSQL: ${binary_type}, set in application(-prod).properties.

CREATE TABLE IF NOT EXISTS job_posting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    title VARCHAR(120) NOT NULL,
    business VARCHAR(20) NOT NULL CHECK (business IN ('GROUP','CONSTRUCTION','FINISHING_WORKS','ESTATE')),
    department VARCHAR(120),
    location VARCHAR(120) NOT NULL,
    work_mode VARCHAR(20) NOT NULL CHECK (work_mode IN ('ON_SITE','HYBRID','REMOTE')),
    employment_type VARCHAR(20) NOT NULL CHECK (employment_type IN ('FULL_TIME','PART_TIME','CONTRACT','INTERNSHIP')),
    experience_min_years INTEGER,
    experience_max_years INTEGER,
    salary_min BIGINT,
    salary_max BIGINT,
    show_salary BOOLEAN NOT NULL,
    openings INTEGER,
    summary VARCHAR(300),
    description VARCHAR(10000),
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','OPEN','CLOSED','ARCHIVED')),
    application_deadline DATE,
    published_at TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS job_posting_responsibility (
    job_id BIGINT NOT NULL REFERENCES job_posting (id),
    position INTEGER NOT NULL,
    item VARCHAR(500),
    PRIMARY KEY (position, job_id)
);

CREATE TABLE IF NOT EXISTS job_posting_requirement (
    job_id BIGINT NOT NULL REFERENCES job_posting (id),
    position INTEGER NOT NULL,
    item VARCHAR(500),
    PRIMARY KEY (position, job_id)
);

CREATE TABLE IF NOT EXISTS job_posting_nice_to_have (
    job_id BIGINT NOT NULL REFERENCES job_posting (id),
    position INTEGER NOT NULL,
    item VARCHAR(500),
    PRIMARY KEY (position, job_id)
);

CREATE TABLE IF NOT EXISTS job_posting_benefit (
    job_id BIGINT NOT NULL REFERENCES job_posting (id),
    position INTEGER NOT NULL,
    item VARCHAR(500),
    PRIMARY KEY (position, job_id)
);

CREATE TABLE IF NOT EXISTS resume_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_filename VARCHAR(120) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    storage_key VARCHAR(200) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS resume_blob (
    id VARCHAR(36) NOT NULL PRIMARY KEY,
    data ${binary_type} NOT NULL
);

CREATE TABLE IF NOT EXISTS job_application (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT REFERENCES job_posting (id),
    name VARCHAR(120) NOT NULL,
    email VARCHAR(200) NOT NULL,
    phone VARCHAR(10) NOT NULL,
    current_location VARCHAR(120),
    total_experience_years NUMERIC(4,1),
    current_company VARCHAR(120),
    notice_period VARCHAR(20) CHECK (notice_period IN ('IMMEDIATE','DAYS_15','DAYS_30','DAYS_60','DAYS_90')),
    expected_salary BIGINT,
    linkedin_url VARCHAR(300),
    portfolio_url VARCHAR(300),
    cover_letter VARCHAR(3000),
    resume_id BIGINT NOT NULL UNIQUE REFERENCES resume_file (id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('NEW','REVIEWED','SHORTLISTED','INTERVIEW','OFFERED','HIRED','REJECTED')),
    admin_notes VARCHAR(5000),
    consent BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS application_status_change (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES job_application (id),
    from_status VARCHAR(20) CHECK (from_status IN ('NEW','REVIEWED','SHORTLISTED','INTERVIEW','OFFERED','HIRED','REJECTED')),
    to_status VARCHAR(20) NOT NULL CHECK (to_status IN ('NEW','REVIEWED','SHORTLISTED','INTERVIEW','OFFERED','HIRED','REJECTED')),
    note VARCHAR(500),
    changed_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_job_application_job ON job_application (job_id);
CREATE INDEX IF NOT EXISTS idx_application_status_change_application ON application_status_change (application_id);
