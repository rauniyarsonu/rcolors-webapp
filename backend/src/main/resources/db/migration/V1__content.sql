-- Estate. Public ids/slugs (lko-p-001, gomti-nagar) are what URLs and cross-references use.

CREATE TABLE location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    published BOOLEAN NOT NULL,
    sort_order INTEGER NOT NULL,
    version BIGINT NOT NULL,
    is_sample BOOLEAN NOT NULL,
    public_id VARCHAR(120) NOT NULL UNIQUE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    location_type VARCHAR(20) NOT NULL,
    parent_id BIGINT REFERENCES location (id),
    enabled BOOLEAN NOT NULL,
    nearby VARCHAR(4000),
    lat DOUBLE PRECISION,
    lng DOUBLE PRECISION,
    aliases VARCHAR(4000),
    landmarks VARCHAR(4000),
    trending BOOLEAN NOT NULL,
    to_confirm BOOLEAN NOT NULL
);
CREATE INDEX idx_location_parent ON location (parent_id);

