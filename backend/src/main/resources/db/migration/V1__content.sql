-- Portable between H2 (local) and PostgreSQL (prod): identity columns, VARCHAR for text,
-- JSON stored as VARCHAR text (see content/JsonConverters). Lists keep their order inside the JSON.

-- Form tables existed before Flyway (ddl-auto=update), hence IF NOT EXISTS.
CREATE TABLE IF NOT EXISTS contact_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    business VARCHAR(255),
    message VARCHAR(5000),
    created_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS estate_enquiry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    interest VARCHAR(255),
    message VARCHAR(5000),
    listing VARCHAR(500),
    city VARCHAR(255),
    page VARCHAR(2000),
    created_at TIMESTAMP(6) WITH TIME ZONE
);

